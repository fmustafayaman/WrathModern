#!/usr/bin/env python3
"""Generate 32-bit/native DBC field maps from the decompilation's offset comments.

The supported databases are the ones edited by the captured 0x41D version-200
content. Unknown layouts must be implemented, not silently treated as successful.
"""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "WoW/Source/Net/NetClient/BuckDatabaseLayouts.inl"
DATABASES = {
    0x00AD305C: 56,
    0x00AD35B4: 16,
    0x00AD3D4C: 32,
    0x00AD3E00: 64,
    0x00AD4040: 68,
    0x00AD4160: 72,
    0x00AD4184: 28,
    0x00AD49D0: 680,
}


def main():
    source = (ROOT / "WoW/Source/DB/DBClient/DBClient.cpp").read_text()
    pattern = r"// STATIC: (0x[0-9A-Fa-f]+)\s+(WowClientDB(?:_RLE)?<([^>]+)>) (\w+);"
    bindings = []
    output = ["// Generated by Tools/Wardendump/generate-buck-layouts.py.\n",
              "// Source: original 32-bit offsets in DB/Rec/*.h; native offsets use offsetof.\n\n"]
    for match in re.finditer(pattern, source):
        address = int(match[1], 16)
        if address not in DATABASES:
            continue
        record, variable, size = match[3], match[4], DATABASES[address]
        header = (ROOT / ("WoW/Source/DB/Rec/%s.h" % record)).read_text()
        fields = re.findall(r"/\* ([0-9A-Fa-f]{4}) \*/\s+[^;\n]+?\b(m_\w+)\s*(?:\[[^;]+\])?\s*;", header)
        if not fields or fields[0] != ("0000", "m_id"):
            raise SystemExit("Missing original ID/field offsets for " + record)
        output.append("static const RecordField s_%sFields[] = {\n" % record)
        for offset, member in fields:
            if int(offset, 16) >= size:
                raise SystemExit("Field outside captured record stride: " + record + "." + member)
            output.append("    BUCK_RECORD_FIELD(%s, 0x%s, %s),\n" % (record, offset, member))
        output.append("};\n\n")
        bindings.append((address, size, record, variable))
    if len(bindings) != len(DATABASES):
        raise SystemExit("Not all captured database globals have a native binding")
    output.append("#define BUCK_DATABASE_BINDINGS(X) \\\n")
    for index, (address, size, record, variable) in enumerate(bindings):
        continuation = " \\\n" if index + 1 < len(bindings) else "\n"
        output.append("    X(0x%08X, %u, %s, %s)" % (address, size, record, variable) + continuation)
    OUTPUT.write_text("".join(output))
    print("Generated %u database bindings: %s" % (len(bindings), OUTPUT.relative_to(ROOT)))


if __name__ == "__main__":
    main()
